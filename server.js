
require("dotenv").config();

const express = require("express");
const nodemailer = require("nodemailer");
const crypto = require("crypto");
const path = require("path");

const app = express();
const PORT = process.env.PORT || 3000;
const sessions = new Map();

app.use(express.json({ limit: "10kb" }));
app.use(express.static(path.join(__dirname, "public")));

const transporter = nodemailer.createTransport({
  service: "gmail",
  auth: {
    user: process.env.GMAIL_USER,
    pass: process.env.GMAIL_APP_PASSWORD
  }
});

function getSession(id) {
  const s = sessions.get(id);
  if (!s || s.expiresAt < Date.now()) {
    if (id) sessions.delete(id);
    return null;
  }
  return s;
}

// Step 1: Create a temporary session.
app.post("/api/start", (req, res) => {
  const { phone, email } = req.body || {};

  if (
    typeof phone !== "string" ||
    !/^\+?[0-9 ()-]{8,16}$/.test(phone) ||
    typeof email !== "string" ||
    !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email) ||
    phone.length > 20 ||
    email.length > 254
  ) {
    return res.status(400).json({ error: "Invalid phone or email." });
  }

  console.log(phone)
  const sessionId = crypto.randomUUID();

  sessions.set(sessionId, {
    email,
    expiresAt: Date.now() + 10 * 60 * 1000,
    codeHash: null,
    codeExpiresAt: 0,
    attempts: 0,
    lastSentAt: 0,
    phone,
    verified: false
  });

  res.json({ sessionId, phone });
});

// Step 2: Email location notification only after consent.
app.post("/api/location", async (req, res) => {
  const { sessionId, consent, latitude, longitude } = req.body || {};

  const s = getSession(sessionId);

  if (!s) {
    return res.status(400).json({ error: "Session expired. Start again." });
  }
  if (consent !== true) {
    return res.status(403).json({ error: "Location consent required." });
  }
  if (
    typeof latitude !== "number" ||
    typeof longitude !== "number" ||
    !Number.isFinite(latitude) ||
    !Number.isFinite(longitude) ||
    latitude < -90 || latitude > 90 ||
    longitude < -180 || longitude > 180
  ) {
    return res.status(400).json({ error: "Invalid coordinates." });
  }

  try {
    await transporter.sendMail({
      from: process.env.GMAIL_USER,
      to: process.env.OWNER_EMAIL,
      subject: "Mobile number of a user",
      text:
        "A participant explicitly consented to share their location.\n" +
        `Latitude: ${latitude}\nLongitude: ${longitude}\n ` +
        "This notification was generated by the college demo."
    });
    res.json({ success: true });
  } catch (err) {
    console.error("Location email failed:", err.message);
    res.status(500).json({ error: "Could not send location email." });
  }
});

